import os

from src.database.sql import sequence_row_source

from .base import BaseWorkload

class TiDBWorkload(BaseWorkload):
    """
    TiDB 工作负载。
    生成用于 TiDB 分布式数据库的示例数据。
    数据文件：CSV 格式
    初始化：生成 init.sql（CREATE TABLE + INSERT）
    """

    DATA_FILE = "users.csv"

    def __init__(self, workload_root: str = None, row_count: int = 1000):
        super().__init__("tidb", workload_root)
        self.data_file = os.path.join(self.data_dir, self.DATA_FILE)
        self.row_count = row_count

    def prepare(self):
        """
        准备工作：
        1. 检查数据文件是否存在，不存在则生成
        2. 生成 init.sql
        """
        print(f"[Workload:TiDBWorkload] Preparing workload at {self.workload_dir}")

        self.ensure_dir(self.workload_dir)
        self.ensure_dir(self.data_dir)

        if not os.path.exists(self.data_file):
            print(f"[Workload:TiDBWorkload] Data file not found: {self.data_file}")
            print(f"[Workload:TiDBWorkload] Generating sample data...")
            self._generate_sample_data()

        print(f"[Workload:TiDBWorkload] Data file ready: {self.data_file}")

        self._generate_init_sql()

        manifest = {
            "workload_name": self.workload_name,
            "data_file": self.data_file,
            "init_sql": self.get_init_sql_path(),
            "tables": ["demo_users", "demo_orders", "demo_products"]
        }
        self.save_manifest(manifest)
        print(f"[Workload:TiDBWorkload] Manifest saved: {self.manifest_path}")
        print(f"[Workload:TiDBWorkload] Init SQL ready: {self.get_init_sql_path()}")

    def _generate_sample_data(self):
        """生成示例 CSV 数据"""
        import random
        from datetime import datetime, timedelta

        csv_content = "id,username,email,created_at\n"
        base_date = datetime(2024, 1, 1)

        for i in range(1, self.row_count + 1):
            username = f"user_{i}"
            email = f"user_{i}@example.com"
            days_offset = random.randint(0, 365)
            created_at = (base_date + timedelta(days=days_offset)).strftime("%Y-%m-%d %H:%M:%S")
            csv_content += f"{i},{username},{email},{created_at}\n"

        with open(self.data_file, 'w') as f:
            f.write(csv_content)
        print(f"[Workload:TiDBWorkload] Generated {self.row_count} rows of sample data: {self.data_file}")

    def _generate_init_sql(self):
        """生成 init.sql（包含 schema 创建和数据导入）"""
        users_values = []
        base_date = "2024-01-01 00:00:00"
        for i in range(1, min(self.row_count, 100) + 1):
            users_values.append(f"({i}, 'user_{i}', 'user_{i}@example.com', '{base_date}')")

        init_sql = f"""-- TiDB workload initialization
-- Generated by TiDBWorkload

-- Create database if not exists
CREATE DATABASE IF NOT EXISTS test;

USE test;

-- Create users table
CREATE TABLE IF NOT EXISTS demo_users (
    id BIGINT PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    created_at DATETIME NOT NULL
);

-- Create products table
CREATE TABLE IF NOT EXISTS demo_products (
    id BIGINT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    price DECIMAL(10, 2) NOT NULL,
    category VARCHAR(50) NOT NULL
);

-- Create orders table
CREATE TABLE IF NOT EXISTS demo_orders (
    id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INT NOT NULL,
    order_time DATETIME NOT NULL,
    FOREIGN KEY (user_id) REFERENCES demo_users(id),
    FOREIGN KEY (product_id) REFERENCES demo_products(id)
);

-- Create indexes for better TiDB performance
CREATE INDEX idx_users_username ON demo_users(username);
CREATE INDEX idx_orders_user_id ON demo_orders(user_id);
CREATE INDEX idx_orders_product_id ON demo_orders(product_id);

-- Insert sample users data
INSERT INTO demo_users (id, username, email, created_at) VALUES
{','.join(users_values)};

-- Insert sample products
INSERT INTO demo_products (id, name, price, category) VALUES
(1, 'Laptop', 5999.00, 'Electronics'),
(2, 'Phone', 2999.00, 'Electronics'),
(3, 'Tablet', 1999.00, 'Electronics'),
(4, 'Headphones', 299.00, 'Accessories'),
(5, 'Keyboard', 199.00, 'Accessories'),
(6, 'Mouse', 99.00, 'Accessories'),
(7, 'Monitor', 1299.00, 'Electronics'),
(8, 'Chair', 899.00, 'Furniture'),
(9, 'Desk', 1299.00, 'Furniture'),
(10, 'Lamp', 199.00, 'Furniture');

-- Insert sample orders (references users and products)
INSERT INTO demo_orders (id, user_id, product_id, quantity, order_time) VALUES
(1, 1, 1, 1, '2024-06-01 10:00:00'),
(2, 1, 4, 2, '2024-06-02 11:00:00'),
(3, 2, 2, 1, '2024-06-03 12:00:00'),
(4, 3, 3, 1, '2024-06-04 13:00:00'),
(5, 2, 5, 1, '2024-06-05 14:00:00');
"""
        init_sql_path = self.get_init_sql_path()
        with open(init_sql_path, 'w') as f:
            f.write(init_sql)
        print(f"[Workload:TiDBWorkload] Generated init.sql: {init_sql_path}")


class TiDBStatisticsDriftWorkload(BaseWorkload):
    """Seed the QP04 shards and the separate table used for benign I/O noise."""

    def __init__(
        self,
        *,
        database: str,
        tables: tuple[str, ...],
        index_name: str,
        status_index_name: str,
        target_value: str,
        status_value: str,
        initial_rows: int,
        initial_target_rows: int,
        maintenance_table: str,
        maintenance_rows: int,
    ):
        super().__init__(f"tidb-mf-qp04-{database}")
        self.database = database
        self.tables = tables
        self.index_name = index_name
        self.status_index_name = status_index_name
        self.target_value = target_value
        self.status_value = status_value
        self.initial_rows = initial_rows
        self.initial_target_rows = initial_target_rows
        self.maintenance_table = maintenance_table
        self.maintenance_rows = maintenance_rows

    def prepare(self):
        self.ensure_dir(self.workload_dir)
        table_sql = []
        for table in self.tables:
            table_sql.extend((
                f"CREATE TABLE IF NOT EXISTS {self.database}.{table} ("
                "id BIGINT NOT NULL PRIMARY KEY, "
                "routing_key VARCHAR(16) NOT NULL, "
                "status VARCHAR(16) NOT NULL, "
                "amount DECIMAL(12,2) NOT NULL, "
                "payload VARCHAR(64) NOT NULL, "
                f"KEY {self.index_name} (routing_key), "
                f"KEY {self.status_index_name} (status))",
                f"INSERT INTO {self.database}.{table} "
                "(id, routing_key, status, amount, payload) "
                f"SELECT n, IF(n <= {self.initial_target_rows}, '{self.target_value}', 'r03'), "
                f"IF(n > {self.initial_target_rows} AND n <= {self.initial_target_rows * 2}, '{self.status_value}', 'closed'), "
                "CAST(n AS DECIMAL(12,2)), CONCAT('bootstrap-', n) "
                f"FROM ({sequence_row_source(self.initial_rows)}) source",
                f"ANALYZE TABLE {self.database}.{table}",
            ))
        table_sql.extend((
            f"CREATE TABLE IF NOT EXISTS {self.database}.{self.maintenance_table} ("
            "id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY, "
            "routing_key VARCHAR(16) NOT NULL, "
            "status VARCHAR(16) NOT NULL, "
            "amount DECIMAL(12,2) NOT NULL, "
            "payload VARCHAR(240) NOT NULL, "
            "KEY idx_mf_qp04_compaction_routing (routing_key), "
            "KEY idx_mf_qp04_compaction_status (status), "
            "KEY idx_mf_qp04_compaction_payload (payload))",
            f"INSERT INTO {self.database}.{self.maintenance_table} "
            "(routing_key, status, amount, payload) "
            "SELECT IF(n % 2 = 0, 'r91', 'r92'), "
            "IF(n % 3 = 0, 'closed', 'open'), "
            "CAST(n AS DECIMAL(12,2)), RPAD('initial-compaction-', 240, 'x') "
            f"FROM ({sequence_row_source(self.maintenance_rows)}) source",
            f"ANALYZE TABLE {self.database}.{self.maintenance_table}",
        ))
        init_sql = "\n".join([
            f"CREATE DATABASE IF NOT EXISTS {self.database};",
            *[f"{statement};" for statement in table_sql],
        ]) + "\n"
        with open(self.get_init_sql_path(), "w", encoding="utf-8") as handle:
            handle.write(init_sql)
        self.save_manifest({
            "workload_name": self.workload_name,
            "init_sql": self.get_init_sql_path(),
            "database": self.database,
            "tables": list(self.tables),
            "rows_per_table": self.initial_rows,
            "maintenance_table": self.maintenance_table,
            "maintenance_rows": self.maintenance_rows,
        })
