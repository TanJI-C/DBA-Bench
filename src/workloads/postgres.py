import hashlib
import json
import os

from .base import BaseWorkload

class DemoWorkload(BaseWorkload):
    """
    Demo 工作负载。
    数据文件：CSV 格式（按 dataset manifest 合同命名为 <table>.dat）
    初始化：生成 init.sql（CREATE TABLE + COPY FROM）
    """

    DATA_FILE = "demo_users.dat"

    def __init__(self, workload_root: str = None):
        super().__init__("demo", workload_root)
        self.data_file = os.path.join(self.data_dir, self.DATA_FILE)

    def prepare(self):
        """
        准备工作：
        1. 检查数据文件是否存在，不存在则生成
        2. 生成 init.sql
        3. 写入 dataset manifest（v3 合同，字段与 deployment._dataset_ready_label 校验一致）
        """
        print(f"[Workload:DemoWorkload] Preparing workload at {self.workload_dir}")

        self.ensure_dir(self.workload_dir)
        self.ensure_dir(self.data_dir)

        if not os.path.exists(self.data_file):
            print(f"[Workload:DemoWorkload] Data file not found: {self.data_file}")
            print(f"[Workload:DemoWorkload] Generating sample data...")
            self._generate_sample_data()

        print(f"[Workload:DemoWorkload] Data file ready: {self.data_file}")

        self._generate_init_sql()

        with open(self.data_file, 'rb') as f:
            data_bytes = f.read()
        init_sql_path = self.get_init_sql_path()
        with open(init_sql_path, 'rb') as f:
            init_digest = hashlib.sha256(f.read()).hexdigest()

        manifest = {
            "workload_name": self.workload_name,
            "scale": 1,
            "required_tables": ["demo_users"],
            "data_files": {
                self.DATA_FILE: {
                    "size_bytes": len(data_bytes),
                    "sha256": hashlib.sha256(data_bytes).hexdigest(),
                }
            },
            "init_sql_sha256": init_digest,
            "schema_sha256": init_digest,
            "schema_source": "init.sql",
        }
        manifest["dataset_fingerprint"] = hashlib.sha256(
            json.dumps(manifest, ensure_ascii=True, sort_keys=True).encode("utf-8")
        ).hexdigest()
        self.save_manifest(manifest)
        print(f"[Workload:DemoWorkload] Manifest saved: {self.manifest_path}")
        print(f"[Workload:DemoWorkload] Init SQL ready: {init_sql_path}")

    def _generate_sample_data(self):
        """生成示例 CSV 数据"""
        csv_content = """id,username,email,created_at
1,alice,alice@example.com,2026-01-01 10:00:00
2,bob,bob@example.com,2026-01-02 11:00:00
3,charlie,charlie@example.com,2026-01-03 12:00:00
4,david,david@example.com,2026-01-04 13:00:00
5,eve,eve@example.com,2026-01-05 14:00:00
"""
        with open(self.data_file, 'w') as f:
            f.write(csv_content)
        print(f"[Workload:DemoWorkload] Generated sample data: {self.data_file}")

    def _generate_init_sql(self):
        """生成 init.sql（包含 schema 创建和数据导入）"""
        container_data_path = f"/workload_data/{self.DATA_FILE}"
        init_sql = """-- Demo workload initialization
-- Generated by DemoWorkload

-- Create table schema
CREATE TABLE IF NOT EXISTS demo_users (
    id INTEGER,
    username VARCHAR(50),
    email VARCHAR(100),
    created_at TIMESTAMP
);

-- Copy data from CSV
\\COPY demo_users (id, username, email, created_at) FROM '{csv_path}' WITH (FORMAT csv, HEADER true);

-- Create primary key
ALTER TABLE demo_users ADD PRIMARY KEY (id);
"""
        init_sql = init_sql.format(csv_path=container_data_path)

        init_sql_path = self.get_init_sql_path()
        with open(init_sql_path, 'w') as f:
            f.write(init_sql)
        print(f"[Workload:DemoWorkload] Generated init.sql: {init_sql_path}")


class SysbenchWorkload(BaseWorkload):
    """
    Sysbench 工作负载。
    用于生成标准的 sysbench 测试数据。
    """

    def __init__(self, workload_root: str = None, tables_count: int = 4, table_size: int = 10000):
        super().__init__("sysbench", workload_root)
        self.tables_count = tables_count
        self.table_size = table_size

    def prepare(self):
        """准备 sysbench 工作负载"""
        print(f"[Workload:SysbenchWorkload] Preparing workload at {self.workload_dir}")

        self.ensure_dir(self.workload_dir)
        self.ensure_dir(self.data_dir)

        print(f"[Workload:SysbenchWorkload] Sysbench workload (tables={self.tables_count}, size={self.table_size})")

        self._generate_init_sql()

        manifest = {
            "workload_name": self.workload_name,
            "tables_count": self.tables_count,
            "table_size": self.table_size,
            "init_sql": self.get_init_sql_path(),
            "tables": [f"sbtest{i}" for i in range(1, self.tables_count + 1)]
        }
        self.save_manifest(manifest)
        print(f"[Workload:SysbenchWorkload] Manifest saved: {self.manifest_path}")

    def _generate_init_sql(self):
        """生成 sysbench init.sql"""
        init_sql = """-- Sysbench workload initialization
-- Generated by SysbenchWorkload

"""
        for i in range(1, self.tables_count + 1):
            init_sql += f"""CREATE TABLE IF NOT EXISTS sbtest{i} (
    id SERIAL PRIMARY KEY,
    k INTEGER DEFAULT 0,
    c CHAR(120) DEFAULT '',
    pad CHAR(60) DEFAULT ''
);

"""
        init_sql += "-- Sysbench data generation should be done via pg_batch_insert or similar tool\n"
        init_sql += "-- For now, tables are created but not populated\n"

        init_sql_path = self.get_init_sql_path()
        with open(init_sql_path, 'w') as f:
            f.write(init_sql)
